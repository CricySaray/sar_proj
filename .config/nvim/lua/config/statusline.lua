-- =============================================================================
--  statusline.lua
--  迁移自原 vimrc 的状态栏格式（无需任何插件，纯 vim 内置）。
--  原格式：%n\ %F%m%r%h%w%=\ \ \ \ \ \ %l/%L,\ %c/%{col('$')-1}\ \ \ --%p%%--
-- =============================================================================

vim.opt.statusline = table.concat({
  "%n",                                                    -- buffer 编号
  " %F%m%r%h%w",                                           -- 文件名 + 修改/只读/帮助等标记
  "%=",                                                    -- 分隔符（左对齐 / 右对齐）
  "     ",                                                 -- 视觉间距
  "%l/%L,",                                                -- 当前行 / 总行
  " %c/%{col('$')-1}",                                     -- 当前列 / 总列（最后一列不算换行）
  "   ",
  "--%p%%--",                                              -- 进度百分比
})

-- 始终显示状态栏
vim.opt.laststatus = 2
